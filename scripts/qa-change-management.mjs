import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
const product = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(`${product}/apps/web/package.json`);
const puppeteer = require('puppeteer-core');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'notes-change-ui-'));
const write = (file, text) => { fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true }); fs.writeFileSync(path.join(root, file), text); };
const git = (...args) => execFileSync('git', args, { cwd: root, stdio: 'pipe' }).toString();
write('.github-notes.yaml', 'schema_version: 1\nworkspace:\n  title: Changes QA\n  default_notebook: example\nnotebooks:\n  - id: example\n    title: Example\n    root: notes/example\n');
write('notes/example/a.md', '# A\n\nOriginal A\n');
write('notes/example/b.md', '# B\n\nOriginal B\n');
git('init', '-b', 'main'); git('config', 'user.name', 'QA'); git('config', 'user.email', 'qa@example.com'); git('add', '.'); git('commit', '-m', 'fixture');
write('notes/example/a.md', '# A\n\nUnsaved A\n');
write('notes/example/b.md', '# B\n\nUnrelated B\n');
process.env.MYGITNOTES_SOURCE = 'local'; process.env.MYGITNOTES_LOCAL_PATH = root; delete process.env.VERCEL; delete process.env.APP_URL;
const { createApp } = await import(`${product}/apps/local-server/dist/app.js`);
const server = createServer(createApp(product)); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await puppeteer.launch({ executablePath: process.env.PUPPETEER_EXECUTABLE_PATH || path.join(os.homedir(), '.cache/puppeteer/chrome/linux-131.0.6778.204/chrome-linux64/chrome'), headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage(); await page.setViewport({ width: 1440, height: 1000 });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const assert = (condition, message) => { if (!condition) throw Error(message); };
const press = async label => { const selector = `button[aria-label=${JSON.stringify(label)}]`; await page.waitForSelector(selector); await page.click(selector); };
const row = (file, side) => `[data-change-path=${JSON.stringify(file)}][data-side=${JSON.stringify(side)}]`;
try {
  await page.goto(base, { waitUntil: 'networkidle0' });
  await page.evaluate(() => localStorage.setItem('github_notes_theme', 'github-dark'));
  await page.goto(`${base}/notebooks/example/notes/a.md`, { waitUntil: 'networkidle0' });
  await press('Document tools'); await press('File Git status');
  assert(await page.$eval('button[aria-label="Restore note"]', button => !button.disabled), 'Dirty note opened by direct URL cannot restore');
  await press('Restore note'); await press('Confirm restore note');
  await page.waitForFunction(() => document.querySelector('.cm-content')?.innerText.includes('Original A'));
  assert(fs.readFileSync(path.join(root, 'notes/example/b.md'), 'utf8').includes('Unrelated B'), 'Single note restore changed another file');
  await press('Close note');
  await press('Changes'); await page.waitForSelector('.changes-dialog');
  await page.waitForFunction(() => document.querySelector('.changes-preview pre')?.textContent.includes('+Unrelated B'));
  await press('Stage notes/example/b.md');
  await page.waitForSelector(row('notes/example/b.md', 'staged'));
  write('notes/example/b.md', '# B\n\nLater B\n');
  write('notes/example/new.md', '# New file\n');
  await press('Refresh changes');
  await page.waitForSelector(row('notes/example/b.md', 'working'));
  await page.click(`${row('notes/example/b.md', 'staged')} .changes-file`);
  await page.waitForFunction(() => document.querySelector('.changes-preview pre')?.textContent.includes('+Unrelated B'));
  await page.click(`${row('notes/example/b.md', 'working')} .changes-file`);
  await page.waitForFunction(() => document.querySelector('.changes-preview pre')?.textContent.includes('+Later B'));
  await press('Unstage notes/example/b.md');
  await page.waitForFunction(() => !document.querySelector('[data-change-path="notes/example/b.md"][data-side="staged"]'));
  await press('Stage notes/example/b.md'); await page.waitForSelector(row('notes/example/b.md', 'staged'));
  await page.click(`${row('notes/example/new.md', 'working')} .changes-file`);
  await page.waitForFunction(() => document.querySelector('.changes-preview pre')?.textContent.includes('+# New file'));
  fs.mkdirSync(`${product}/artifacts/qa`, { recursive: true });
  await page.screenshot({ path: `${product}/artifacts/qa/changes-desktop.png` });
  await page.setViewport({ width: 390, height: 844 });
  await page.screenshot({ path: `${product}/artifacts/qa/changes-mobile.png` });
  assert(await page.$eval('.changes-dialog', dialog => { const r = dialog.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.bottom <= innerHeight; }), 'Changes manager overflows mobile viewport');
  await press('Restore notes/example/b.md');
  await press('Restore notes/example/new.md');
  await page.waitForFunction(() => document.querySelector('.changes-confirm')?.textContent.includes('notes/example/new.md'));
  assert(fs.existsSync(path.join(root, 'notes/example/new.md')), 'First restore click discarded the file');
  assert(fs.readFileSync(path.join(root, 'notes/example/b.md'), 'utf8').includes('Later B'), 'Switching confirmation targets restored the previous file');
  await press('Confirm discard');
  await page.waitForFunction(() => !document.querySelector('[data-change-path="notes/example/new.md"]'));
  assert(!fs.existsSync(path.join(root, 'notes/example/new.md')), 'Confirmed discard did not remove new file');
  await page.waitForSelector('input[aria-label="Commit Message"]:not(:disabled)');
  await page.type('input[aria-label="Commit Message"]', 'docs(notes): selected file');
  await page.$$eval('.changes-dialog button', buttons => buttons.find(button => button.textContent.trim() === 'Commit & Save').click());
  await page.waitForFunction(() => !document.querySelector('.changes-dialog'));
  assert(git('show', 'HEAD:notes/example/b.md').includes('Later B'), 'Staged file was not committed');
  assert(git('status', '--porcelain').trim() === '', 'Unexpected remaining changes');
  assert(!errors.length, errors.join('; '));
  console.log('PASS direct-link note restore, isolated files, per-file working/staged diffs, unstage, new-file confirmation, mobile geometry and selected commit');
} catch (error) {
  console.log(await page.evaluate(() => ({ text: document.querySelector('.changes-dialog')?.textContent, alerts: [...document.querySelectorAll('[role="alert"]')].map(node => node.textContent), buttons: [...document.querySelectorAll('.changes-dialog button')].map(button => ({ text: button.textContent, disabled: button.disabled })) })));
  throw error;
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); fs.rmSync(root, { recursive: true, force: true }); }
